// Названия приходят из выгрузок издательств с прямыми кавычками и дефисом вместо тире.
// В вёрстке НЭН это выглядит чужеродно, поэтому нормализуем на этапе сборки каталога.

export function normalizeTypography(value) {
  if (typeof value !== "string") return value;
  return value
    // Парные прямые кавычки → «ёлочки». Одиночная прямая кавычка остаётся как есть:
    // это чаще апостроф внутри имени, чем открывающая кавычка.
    .replace(/"([^"]+)"/gu, "«$1»")
    // Дефис между пробелами — это тире.
    .replace(/ - /gu, " — ")
    .replace(/\s+/gu, " ")
    .trim();
}
