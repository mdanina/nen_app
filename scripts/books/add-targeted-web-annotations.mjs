const overrides = JSON.parse(fs.readFileSync(overridesPath, "utf8"));
const existingIds = new Set(overrides.map((entry) => entry.id));
const additions = annotations
  .filter((entry) => !existingIds.has(entry.id))
  .map((entry) => ({
    id: entry.id,
    description: entry.description,
    source: new URL(entry.sourceUrl).hostname,
    sourceUrl: entry.sourceUrl,
    retrievedAt,
    method: "independent_factual_description",
    evidenceField: "targeted_web_search_title_author",
  }));

fs.writeFileSync(
  overridesPath,
  `${JSON.stringify([...overrides, ...additions], null, 2)}\n`,
  "utf8",
);

