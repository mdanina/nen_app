function list(values) {
  const clean = [...new Set(values.filter(Boolean))];
  if (clean.length < 2) return clean[0] ?? "";
  return `${clean.slice(0, -1).join(", ")} и ${clean.at(-1)}`;
}

function hash(value = "") {
  let result = 0;
  for (const character of value) result = (result * 31 + character.codePointAt(0)) >>> 0;
  return result;
}

function readingPhrase(mode) {
  if (mode === "together") return "совместного чтения со взрослым";
  if (mode === "independent") return "самостоятельного чтения";
  return "самостоятельного или совместного чтения";
}

export function isGeneratedRecommendation(value = "") {
  return /^(?:Подойдёт читателям \d+–\d+ лет, которым (?:интересна тема|нравятся)|Подходит детям \d+–\d+ лет|Помогает поговорить с ребёнком о таких темах|Подходит детям \d+–\d+ лет для совместного знакомства)/u.test(value);
}

export function buildBookRecommendation(book, { force = false } = {}) {
  if (!force && book.whyRecommended?.trim() && !isGeneratedRecommendation(book.whyRecommended)) {
    return book.whyRecommended.trim();
  }

  const age = `${book.ageMin}–${book.ageMax} лет`;
  const genreObject = list((book.genres ?? []).slice(0, 2).map((value) => genreObjects.get(value) ?? value));
  const genreLabel = list((book.genres ?? []).slice(0, 2));
  const themesPrep = list((book.themes ?? []).slice(0, 3).map((value) => themePrepositional.get(value) ?? value));
  const themesGen = list((book.themes ?? []).slice(0, 3).map((value) => themeGenitive.get(value) ?? value));
  const reading = readingPhrase(book.readingMode);

  const variants = [
    `Подойдёт читателям ${age}, которые любят ${genreObject}. В книге затрагиваются темы ${themesGen}.`,
    `Для читателей ${age} это ${genreLabel} о ${themesPrep}. Книгу можно выбрать для ${reading}.`,
    `Если ребёнок любит ${genreObject} и сюжеты о ${themesPrep}, книга подойдёт ему в возрасте ${age}. Она подходит для ${reading}.`,
  ];
  return variants[hash(book.id) % variants.length];
}
